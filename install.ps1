<#
.SYNOPSIS
    Install DSH Tools on this machine: the shared skill root, PATH shims, and the
    local DSH plugins.

.DESCRIPTION
    Run after cloning this repository. Every step is idempotent: re-running makes
    whatever is missing and reports the rest as skipped. Nothing here needs admin
    rights, and nothing outside %USERPROFILE% is touched.

    Steps
      1. Junction %USERPROFILE%\.agents\skills to this repository's skills\ folder,
         so every project (any cwd) discovers these skills.
      2. Write a <name>.cmd shim in %USERPROFILE%\.local\bin for each skills\<name>\
         that ships a <name>.ps1, so harnesses that never read a skill catalog can
         still run the tool.
      3. Register every plugin in this repository (a directory whose package.json
         declares dsh.bundle) into the DSH profile.

.PARAMETER Profile
    DSH profile that receives the plugins. Default: web

.PARAMETER DshCommand
    Command used to invoke dsh, e.g. 'dsh' or 'C:\tools\dsh.exe'. Default: auto-detect
    (dsh on PATH, then $env:DSH_CLI, then a source checkout at $env:DSH_CHECKOUT).

.PARAMETER DryRun
    Print what would change and change nothing.

.EXAMPLE
    pwsh -NoProfile -File .\install.ps1

.EXAMPLE
    pwsh -NoProfile -File .\install.ps1 -DryRun
#>
[CmdletBinding()]
param(
    [string]$Profile = 'web',
    [string]$DshCommand,
    [switch]$DryRun
)

$ErrorActionPreference = 'Stop'
$Repo    = $PSScriptRoot
$Home_   = $env:USERPROFILE
$Skills  = Join-Path $Repo 'skills'
$BinDir  = Join-Path $Home_ '.local\bin'
$AgentsSkills = Join-Path $Home_ '.agents\skills'

$script:Planned = 0
$script:Applied = 0

function Write-Head($text) { Write-Host "`n== $text" -ForegroundColor Cyan }
function Write-Ok($text)   { Write-Host "   ok    $text" -ForegroundColor Green }
function Write-Skip($text) { Write-Host "   skip  $text" -ForegroundColor DarkGray }
function Write-Warn($text) { Write-Host "   warn  $text" -ForegroundColor Yellow }
function Write-Step($text) {
    if ($DryRun) { Write-Host "   plan  $text" -ForegroundColor Magenta; $script:Planned++ }
    else         { Write-Host "   do    $text" -ForegroundColor Cyan;    $script:Applied++ }
}

# --- preconditions ----------------------------------------------------------

if ($PSVersionTable.PSVersion.Major -lt 5) {
    throw "PowerShell 5.1 or newer is required (found $($PSVersionTable.PSVersion))."
}
if (-not (Test-Path $Skills)) {
    throw "No skills\ folder next to this script. Run install.ps1 from the DSH Tools root."
}
if ($env:OS -ne 'Windows_NT') {
    throw "This repository is Windows-only (Win32/GDI capture, junctions, .cmd shims)."
}

Write-Host "DSH Tools installer" -ForegroundColor White
Write-Host "  repo    : $Repo"
Write-Host "  profile : $Profile"
if ($DryRun) { Write-Host "  mode    : dry run, nothing will change" -ForegroundColor Magenta }

# --- 1. shared skill root ---------------------------------------------------

Write-Head 'Shared skill root'

$skillsRoot = (Resolve-Path $Skills).Path
$existing = Get-Item $AgentsSkills -Force -ErrorAction SilentlyContinue

if (-not $existing) {
    Write-Step "create junction $AgentsSkills -> $skillsRoot"
    if (-not $DryRun) {
        New-Item -ItemType Directory -Force -Path (Split-Path $AgentsSkills -Parent) | Out-Null
        New-Item -ItemType Junction -Path $AgentsSkills -Target $skillsRoot | Out-Null
    }
}
elseif ($existing.LinkType -eq 'Junction') {
    $target = @($existing.Target)[0]
    if ($target.TrimEnd('\') -eq $skillsRoot.TrimEnd('\')) {
        Write-Skip "$AgentsSkills already points here"
    }
    else {
        Write-Step "repoint junction $AgentsSkills ($target -> $skillsRoot)"
        if (-not $DryRun) {
            Remove-Item -LiteralPath $AgentsSkills -Force
            New-Item -ItemType Junction -Path $AgentsSkills -Target $skillsRoot | Out-Null
        }
    }
}
else {
    Write-Warn "$AgentsSkills is a real directory, not a junction. Left alone."
    Write-Warn "Move its contents into $skillsRoot, or delete it and re-run."
}

# --- 2. PATH shims ----------------------------------------------------------

Write-Head 'PATH shims'

if (-not (Test-Path $BinDir)) {
    Write-Step "create $BinDir"
    if (-not $DryRun) { New-Item -ItemType Directory -Force -Path $BinDir | Out-Null }
}

$shims = 0
foreach ($dir in Get-ChildItem $Skills -Directory) {
    $ps1 = Join-Path $dir.FullName "$($dir.Name).ps1"
    if (-not (Test-Path $ps1)) { continue }

    $name = $dir.Name
    $shim = Join-Path $BinDir "$name.cmd"
    $body = @(
        '@echo off'
        "rem $name - run the central tool from any directory."
        'rem Generated by DSH Tools install.ps1. Re-run it if this repo moves.'
        'setlocal'
        "pwsh -NoProfile -File `"$ps1`" %*"
    ) -join "`r`n"
    $expected = "$body`r`n"

    if ((Test-Path $shim) -and ((Get-Content $shim -Raw) -eq $expected)) {
        Write-Skip "$name.cmd up to date"
    }
    else {
        Write-Step "write $shim"
        if (-not $DryRun) { Set-Content -LiteralPath $shim -Value $body -Encoding ascii }
    }
    $shims++
}

if ($shims -eq 0) { Write-Warn "no skills\<name>\<name>.ps1 found, nothing to shim" }

$onPath = ($env:PATH -split ';') | Where-Object { $_.TrimEnd('\') -ieq $BinDir.TrimEnd('\') }
if (-not $onPath) {
    Write-Warn "$BinDir is NOT on PATH - add it once, then open a new terminal:"
    Write-Warn "  [Environment]::SetEnvironmentVariable('PATH', [Environment]::GetEnvironmentVariable('PATH','User') + ';$BinDir', 'User')"
}

# --- 3. local plugins -------------------------------------------------------

Write-Head "DSH plugins (profile: $Profile)"

function Resolve-DshCommand {
    param([string]$Explicit)

    if ($Explicit) { return @{ Cmd = @($Explicit); Cwd = $null } }

    $onPathCmd = Get-Command dsh -ErrorAction SilentlyContinue
    if ($onPathCmd) { return @{ Cmd = @($onPathCmd.Source); Cwd = $null } }

    if ($env:DSH_CLI) { return @{ Cmd = @($env:DSH_CLI); Cwd = $null } }

    $checkout = if ($env:DSH_CHECKOUT) { $env:DSH_CHECKOUT } else { 'C:\AI\deepseek-harness' }
    $bin = Join-Path $checkout 'apps\cli\src\bin.ts'
    $node = Get-Command node -ErrorAction SilentlyContinue
    if ((Test-Path $bin) -and $node) {
        return @{ Cmd = @($node.Source, '--import', 'tsx/esm', $bin); Cwd = $checkout }
    }
    return $null
}

$dsh = Resolve-DshCommand -Explicit $DshCommand
if (-not $dsh) {
    Write-Warn "could not find dsh. Pass -DshCommand, set DSH_CLI, or put dsh on PATH."
    Write-Warn "The plugin step is the only thing skipped; skills and shims still apply."
}

$dshHome = if ($env:DSH_HOME) { $env:DSH_HOME } else { Join-Path $Home_ '.dsh' }
$profileManifest = Join-Path $dshHome "profiles\$Profile\package.json"

$plugins = @()
foreach ($dir in Get-ChildItem $Repo -Directory) {
    $manifest = Join-Path $dir.FullName 'package.json'
    if (-not (Test-Path $manifest)) { continue }
    $pkg = Get-Content $manifest -Raw | ConvertFrom-Json
    if ($pkg.dsh -and $pkg.dsh.bundle) {
        $plugins += [pscustomobject]@{ Name = $pkg.name; Path = $dir.FullName }
    }
}

if ($plugins.Count -eq 0) { Write-Warn "no plugin packages found in $Repo" }

foreach ($plugin in $plugins) {
    $installed = $false
    if (Test-Path $profileManifest) {
        $profilePkg = Get-Content $profileManifest -Raw | ConvertFrom-Json
        $inDeps = $profilePkg.dependencies.PSObject.Properties.Name -contains $plugin.Name
        $inBundles = $profilePkg.dsh.profile.bundles -contains $plugin.Name
        $installed = $inDeps -and $inBundles
        if ($inDeps -and -not $inBundles) {
            Write-Warn "$($plugin.Name) is a dependency but missing from bundles; re-adding"
            $installed = $false
        }
    }

    if ($installed) {
        Write-Skip "$($plugin.Name) already installed in profile '$Profile'"
        continue
    }
    if (-not $dsh) {
        Write-Warn "$($plugin.Name) not installed - run this once dsh is available:"
        Write-Warn "  dsh plugin --profile $Profile add `"$($plugin.Path)`""
        continue
    }

    Write-Step "dsh plugin --profile $Profile add `"$($plugin.Path)`""
    if (-not $DryRun) {
        if ($dsh.Cwd) { Push-Location $dsh.Cwd }
        try {
            $argv = @($dsh.Cmd) + @('plugin', '--profile', $Profile, 'add', $plugin.Path)
            & $argv[0] $argv[1..($argv.Length - 1)]
            if ($LASTEXITCODE -ne 0) { throw "dsh plugin exited with code $LASTEXITCODE" }
        }
        finally {
            if ($dsh.Cwd) { Pop-Location }
        }
        Write-Ok "$($plugin.Name) installed"
    }
}

# --- summary ----------------------------------------------------------------

Write-Head 'Done'
if ($DryRun) {
    Write-Host "   $script:Planned change(s) would be made. Re-run without -DryRun to apply." -ForegroundColor Magenta
}
else {
    Write-Host "   $script:Applied change(s) applied." -ForegroundColor Green
    Write-Host "   Skills are discovered from $AgentsSkills on the next DSH session." -ForegroundColor Gray
    Write-Host "   Shims live in $BinDir." -ForegroundColor Gray
}
